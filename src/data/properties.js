export const formatPrice = (price, type) => {
  if (type === 'rent' || type === 'commercial') {
    return `$${price.toLocaleString()}/mo`
  }
  if (price >= 1000000) {
    return `$${(price / 1000000).toFixed(1)}M`
  }
  return `$${price.toLocaleString()}`
}
